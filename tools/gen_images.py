#!/usr/bin/env python3
"""Generate config/images.txt from the module tables in SLUS_008.13.

    python3 tools/gen_images.py game > config/images.txt

T.R.A.G. loads its code in modules (word 0 of each is the module id):
- character modules (ids 4-11): two per character pack PRG/PLAYER/{MIC,BUR,ALE,RAC}_PACK.BIN,
  loaded at 0x80143E08. Their sizes are in the table at 0x80010000 (per character one row of
  four sizes - three modes use the module at the start of the pack, the fourth the second
  module - followed by four rows of entry points).
- cutscene ("demo") modules (ids 0x0C-0x42): DEMOPACK.BIN, at 0x80143E08; sector offsets at
  0x800146E0, sizes at 0x800147BC (55 entries each).
- room modules (ids 0x45-): BGDATA/RM_PACK.BIN, at 0x80161B50; sector offsets at 0x80014C10,
  sizes at 0x80014DD0 (108 entries; an offset of 0 after the first entry is an unused slot).
- SUB0D.BIN and SAVE.BIN, at 0x80143E08 (whole files).
A module is code followed by its data; the image covers only the code part (up to the last
`jr ra` of the run of code at its start), so the data is never swept for functions.
"""
import os
import struct
import sys

game = sys.argv[1]
exe = open(os.path.join(game, 'SLUS_008.13'), 'rb').read()[0x800:]
w = lambda a: struct.unpack_from('<I', exe, a - 0x80010000)[0]

MOD_BASE = 0x80143E08
ROOM_BASE = 0x80161B50


def code_size(data):
    """Length of the code at the start of a module: up to the last jr ra (+ delay slot) before
    a stretch of 24 KB without one (functions here are long: 16 KB between returns occurs)."""
    n = len(data) // 4
    last = None
    for i in range(n):
        if struct.unpack_from('<I', data, 4 * i)[0] == 0x03E00008:
            if last is not None and 4 * i - last > 0x6000:
                break
            last = 4 * i
    return (last + 8) if last is not None else 0


out = ['# Code images for the recompiler (see src/recomp.py). Generated by tools/gen_images.py.',
       '#   exe <file>',
       '#   ovl <file> <load address> <host exe> <archive> <offset> <size>',
       'exe SLUS_008.13']


def ovl(name, base, arc, off, size):
    data = open(os.path.join(game, arc), 'rb').read()[off:off + size]
    cs = code_size(data)
    if cs < 0x100:
        return
    mid = struct.unpack_from('<I', data, 0)[0]
    out.append('ovl overlays/%s.bin %08x SLUS_008.13 %s %07x %06x   # id %02x' % (name, base, arc, off, cs, mid))


ovl('SUB0D', MOD_BASE, 'SUB0D.BIN', 0, os.path.getsize(os.path.join(game, 'SUB0D.BIN')))
ovl('SAVE', MOD_BASE, 'SAVE.BIN', 0, os.path.getsize(os.path.join(game, 'SAVE.BIN')))
second = {'MIC': 0x34000, 'BUR': 0x25800, 'ALE': 0x32800, 'RAC': 0x3B800}
for k, ch in enumerate(['MIC', 'BUR', 'ALE', 'RAC']):
    row = 0x80010000 + k * 0x50
    arc = 'PRG/PLAYER/%s_PACK.BIN' % ch
    ovl('%s_a' % ch, MOD_BASE, arc, 0, w(row))
    ovl('%s_b' % ch, MOD_BASE, arc, second[ch], w(row + 12))
for i in range(55):
    ovl('DEMO_%02d' % i, MOD_BASE, 'PRG/PLAYER/DEMOPACK.BIN', w(0x800146E0 + 4 * i) * 0x800, w(0x800147BC + 4 * i))
for i in range(108):
    sec = w(0x80014C10 + 4 * i)
    if i and not sec:
        continue
    ovl('ROOM_%03d' % i, ROOM_BASE, 'BGDATA/RM_PACK.BIN', sec * 0x800, w(0x80014DD0 + 4 * i))
print('\n'.join(out))
